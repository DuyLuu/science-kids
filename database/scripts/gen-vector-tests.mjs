#!/usr/bin/env node
// Generates database/supabase/tests/vectors_<suite>.test.sql from the shared test vectors in
// packages/content-schema/test-vectors (SK-003, SK-021). One pgTAP assertion per case, so the SQL
// rule functions run exactly the cases the Swift and Kotlin engines run.
//
//   node database/scripts/gen-vector-tests.mjs           write the files
//   node database/scripts/gen-vector-tests.mjs --check   exit 1 when a file is missing or out of date (CI)
//
// Harness rules (test-vectors/README.md): rules = default_rules || case.rules (shallow, like jsonb ||);
// inputs in the order of `function`; compare with expected by jsonb equality (keys unordered,
// arrays ordered, null is not a missing key). Only suites with "server" in `platforms` and an SQL
// implementation below are generated; warmup-selection waits for get_warmup_items.
// Test files hold no BEGIN/ROLLBACK: scripts/db-apply.mjs --test wraps each file in a transaction
// and rolls it back.

import { readFileSync, writeFileSync, existsSync } from 'node:fs';
import { dirname, join, relative } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..', '..');
const vectorsDir = join(root, 'packages', 'content-schema', 'test-vectors');
const testsDir = join(root, 'database', 'supabase', 'tests');
const check = process.argv.includes('--check');

const lit = (value) => `'${String(value).replaceAll("'", "''")}'`;
const json = (value) => `${lit(JSON.stringify(value))}::jsonb`;

// SQL for one case: [have, want] expressions. rules is the merged jsonb expression.
const SUITES = {
  'lesson-score': (input) => [
    `public.score_lesson(${json(input.quiz_results)}, ${json(input.warmup_results)})`,
  ],
  stars: (input, rules) => [`public.compute_stars(${json(input.attempts)}, ${rules})`],
  streak: (input, rules) => [
    `public.compute_streak(${json(input.studied_dates)}, ${lit(input.today)}::date, ${rules})`,
  ],
  // local_date returns a date; the vector expects "YYYY-MM-DD", compared as jsonb like the others.
  'local-date': (input) => [
    `to_jsonb(public.local_date(${lit(input.completed_at)}::timestamptz, ${lit(input.timezone)}))`,
  ],
};

let stale = 0;
for (const [suite, call] of Object.entries(SUITES)) {
  const source = join(vectorsDir, `${suite}.json`);
  const file = JSON.parse(readFileSync(source, 'utf8'));
  if (file.suite !== suite) throw new Error(`${source}: suite is ${file.suite}`);
  if (!file.platforms.includes('server')) throw new Error(`${source}: not a server suite`);

  const lines = [
    `-- GENERATED by database/scripts/gen-vector-tests.mjs from ${relative(root, source)}. Do not edit:`,
    `-- change the vector (tester) or the SQL function, then run the script again.`,
    `-- ${file.function}`,
    `-- ${file.cases.length} cases, vector file version ${file.version}.`,
    '',
    `SELECT plan(${file.cases.length});`,
    '',
  ];
  for (const c of file.cases) {
    const rules = c.rules ? `(${json(file.default_rules)} || ${json(c.rules)})` : json(file.default_rules);
    const [have] = call(c.input, rules);
    lines.push(`SELECT is(${have}, ${json(c.expected)}, ${lit(c.id)});`);
  }
  lines.push('', 'SELECT * FROM finish();', '');

  const target = join(testsDir, `vectors_${suite}.test.sql`);
  const text = lines.join('\n');
  const current = existsSync(target) ? readFileSync(target, 'utf8') : null;
  if (check) {
    if (current !== text) {
      stale++;
      console.log(`out of date: ${relative(root, target)}`);
    }
  } else {
    writeFileSync(target, text);
    console.log(`${relative(root, target)}: ${file.cases.length} cases`);
  }
}

if (check) {
  console.log(stale === 0 ? 'vector tests are up to date' : `${stale} file(s) out of date: run node database/scripts/gen-vector-tests.mjs`);
  process.exit(stale === 0 ? 0 : 1);
}
