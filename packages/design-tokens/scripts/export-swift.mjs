/** Token ids whose generated block is not found as-is in `existingText`. */
export function diffAgainst(existingText, generated) {
  const existingIds = new Set([...existingText.matchAll(MARKER_RE)].map((m) => m[1]));
  const changed = [];
  const added = [];
  for (const [id, block] of generated.blocks) {
    if (existingText.includes(block)) continue;
    (existingIds.has(id) ? changed : added).push(id);
  }
  const removed = [...existingIds].filter((id) => !generated.blocks.has(id));
  const frameOnly = changed.length + added.length + removed.length === 0 && existingText !== generated.text;
  return { changed, added, removed, frameOnly };
}

