function parseArgs(argv) {
  const base = process.env.INIT_CWD ?? process.cwd();
  const args = { check: false, tokens: DEFAULT_TOKENS, out: DEFAULT_OUT };
  for (let i = 0; i < argv.length; i++) {
    const a = argv[i];
    if (a === '--check') args.check = true;
    else if (a === '--tokens' || a === '--out') {
      const v = argv[++i];
      if (!v) throw new TokenError(`${a} cần đường dẫn`);
      args[a.slice(2)] = resolve(base, v);
    } else if (a === '--help' || a === '-h') args.help = true;
    else throw new TokenError(`tham số lạ: ${a}`);
  }
  return args;
}

function main() {
  const args = parseArgs(process.argv.slice(2));
  if (args.help) {
    console.log('node scripts/export-swift.mjs [--check] [--tokens <tokens.json>] [--out <Tokens.swift>]');
    return 0;
  }
  const rel = (p) => {
    const r = relative(REPO_DIR, p);
    return r && !r.startsWith('..') ? r : p;
  };
  const tokens = JSON.parse(readFileSync(args.tokens, 'utf8'));
  const gen = generateSwift(tokens);
  const counts = `Lá trong ${rel(args.tokens)}: ${gen.leafCount} · Hằng trong Tokens.swift: ${gen.constantCount}`;
  if (gen.leafCount !== gen.constantCount) {
    console.error(`${counts}\nLỗi: số lá khác số hằng.`);
    return 1;
  }

  if (!args.check) {
    const before = existsSync(args.out) ? readFileSync(args.out, 'utf8') : null;
    if (before !== gen.text) {
      mkdirSync(dirname(args.out), { recursive: true });
      writeFileSync(args.out, gen.text);
    }
    console.log(`${before === gen.text ? 'Không đổi' : 'Đã ghi'}: ${rel(args.out)}`);
    console.log(counts);
    return 0;
  }

  if (!existsSync(args.out)) {
    console.error(`check:swift: chưa có ${rel(args.out)}. Chạy: cd packages/design-tokens && npm run export:swift`);
    return 1;
  }
  const existing = readFileSync(args.out, 'utf8');
  console.log(counts);
  if (existing === gen.text) {
    console.log(`check:swift: ${rel(args.out)} khớp ${rel(args.tokens)}.`);
    return 0;
  }
  const d = diffAgainst(existing, gen);
  console.error(`check:swift: ${rel(args.out)} lệch với ${rel(args.tokens)}.`);
  for (const id of d.changed) console.error(`  lệch: ${id}`);
  for (const id of d.added) console.error(`  thiếu trong Tokens.swift: ${id}`);
  for (const id of d.removed) console.error(`  thừa trong Tokens.swift: ${id}`);
  if (d.frameOnly) console.error('  khác ở phần khung (header, kiểu), không ở token nào.');
  console.error('Chạy: cd packages/design-tokens && npm run export:swift');
  return 1;
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  try {
    process.exitCode = main();
  } catch (err) {
    if (err instanceof TokenError || err instanceof SyntaxError) {
      console.error(`export-swift: ${err.message}`);
      process.exitCode = 1;
    } else {
      throw err;
    }
  }
}
