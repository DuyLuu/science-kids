// Generation

/**
 * @returns {{ text: string, leafCount: number, constantCount: number, blocks: Map<string, string> }}
 */
export function generateSwift(tokens) {
  const { leaves } = readTree(tokens);
  const byId = new Map(leaves.map((l) => [l.id, l]));
  const { top, leafSwiftPath } = buildContainers(tokens);

  const resolveRef = (ref, where, expectedType) => {
    const m = REF_RE.exec(ref);
    if (!m) return null;
    const target = byId.get(m[1]);
    if (!target) throw new TokenError(`${where}: tham chiếu ${ref} không trỏ tới lá nào`);
    if (expectedType && target.type !== expectedType) {
      throw new TokenError(`${where}: tham chiếu ${ref} có $type ${target.type}, cần ${expectedType}`);
    }
    return { target, swift: leafSwiftPath.get(target.id) };
  };

  const checkRefsInside = (value, where) => {
    if (typeof value === 'string' && value.startsWith('{')) {
      if (!resolveRef(value, where)) throw new TokenError(`${where}: tham chiếu sai cú pháp ${value}`);
    } else if (Array.isArray(value)) value.forEach((v, i) => checkRefsInside(v, `${where}[${i}]`));
    else if (isObject(value)) for (const [k, v] of Object.entries(value)) checkRefsInside(v, `${where}.${k}`);
  };

  const described = new Map();
  const describing = new Set();

  /** → { type, lines, note } for one leaf. */
  const describe = (leaf) => {
    if (described.has(leaf.id)) return described.get(leaf.id);
    if (describing.has(leaf.id)) throw new TokenError(`${leaf.id}: tham chiếu vòng`);
    describing.add(leaf.id);
    let out;
    const { id, type, value } = leaf;
    const ref = typeof value === 'string' ? resolveRef(value, id, type) : null;
    if (ref) {
      out = { type: describe(ref.target).type, lines: [ref.swift], note: `→ \`${ref.target.id}\`` };
    } else {
      out = describeValue(leaf, { resolveRef, checkRefsInside });
    }
    describing.delete(leaf.id);
    described.set(leaf.id, out);
    return out;
  };

  const blocks = new Map();
  const body = [];

  const emitContainer = (container, indent, isTop) => {
    const pad = ' '.repeat(indent);
    const out = [];
    const groupDoc = container.description ? ` ${oneLine(container.description)}` : '';
    if (isTop && container.kind === 'extension') {
      out.push(`// MARK: - ${container.id}`, '');
      out.push(`/// Nhóm \`${container.id}\`.${groupDoc}`);
      out.push(`extension ${container.swiftPath.join('.')} {`);
    } else if (isTop) {
      out.push(`// MARK: - ${container.id}`, '');
      out.push('extension Tokens {');
      out.push(`${pad}/// Nhóm \`${container.id}\`.${groupDoc}`);
      out.push(`${pad}public enum ${container.name} {`);
    } else {
      out.push(`${pad}/// Nhóm \`${container.id}\`.${groupDoc}`);
      out.push(`${pad}public enum ${container.name} {`);
    }
    const inner = isTop && container.kind === 'extension' ? indent : indent + 4;
    const innerPad = ' '.repeat(inner);
    container.items.forEach((item, i) => {
      if (i > 0) out.push('');
      if (item.group) {
        out.push(...emitContainer(item.group, inner, false));
        return;
      }
      const leaf = byId.get(item.leafId);
      const d = describe(leaf);
      const block = [];
      block.push(`${innerPad}/// \`${leaf.id}\`${d.note ? ` ${d.note}` : ''}`);
      if (leaf.description) block.push(`${innerPad}/// ${oneLine(leaf.description)}`);
      const [first, ...rest] = d.lines;
      block.push(`${innerPad}public static let ${item.name}: ${d.type} = ${first}`);
      for (const l of rest) block.push(`${innerPad}${l}`);
      const text = block.join('\n');
      blocks.set(leaf.id, text);
      out.push(text);
    });
    if (isTop && container.kind === 'extension') {
      out.push('}');
    } else {
      out.push(`${pad}}`);
      if (isTop) out.push('}');
    }
    return out;
  };

  for (const container of top) {
    body.push(...emitContainer(container, 4, true), '');
  }

  body.push(...emitAgeLookups(byId, leafSwiftPath));

  const text = [
    HEADER,
    '// Source: packages/design-tokens/tokens.json. Regenerate with `cd packages/design-tokens && npm run export:swift`;',
    '// `npm run check:swift` fails when this file is out of date. Mapping rules: packages/design-tokens/README.md, "Xuất Swift".',
    `// ${leaves.length} tokens, one \`public static let\` each. Units: pt, seconds (tokens.json stores ms), Angle for degrees.`,
    '',
    'import Foundation',
    'import SwiftUI',
    '',
    ...TYPES,
    '',
    ...body,
  ].join('\n').replace(/\n*$/, '\n');

  const constantCount = (text.match(/^[ \t]*public static let /gm) ?? []).length;
  const markers = [...text.matchAll(MARKER_RE)].map((m) => m[1]);
  if (markers.length !== leaves.length || new Set(markers).size !== markers.length) {
    throw new TokenError(`lỗi export-swift.mjs: ${markers.length} dấu token cho ${leaves.length} lá`);
  }
  return { text, leafCount: leaves.length, constantCount, blocks };
}

function oneLine(s) {
  return String(s).replace(/\s*\n\s*/g, ' ').trim();
}

function describeValue(leaf, { resolveRef, checkRefsInside }) {
  const { id, type, value, key } = leaf;
  switch (type) {
    case 'color':
      return { type: 'Color', lines: [colorLiteral(value, id)], note: String(value).toUpperCase() };
    case 'dimension':
      return { type: 'CGFloat', lines: [num(value, id)] };
    case 'duration':
      return { type: 'TimeInterval', lines: [msToSeconds(value, id)], note: `(${num(value, id)} ms)` };
    case 'number':
      if (key.startsWith('tilt_')) return { type: 'Angle', lines: [`.degrees(${num(value, id)})`], note: '(độ)' };
      if (key.endsWith('_scale')) return { type: 'CGFloat', lines: [num(value, id)] };
      if (Number.isInteger(value)) return { type: 'Int', lines: [int(value, id)] };
      return { type: 'Double', lines: [num(value, id)] };
    case 'string':
      if (typeof value !== 'string') throw new TokenError(`${id}: $type string cần chuỗi`);
      if (key.endsWith('_category')) {
        if (!DYNAMIC_TYPE_SIZES.includes(value)) {
          throw new TokenError(`${id}: "${value}" không phải DynamicTypeSize (${DYNAMIC_TYPE_SIZES.join(', ')})`);
        }
        return { type: 'DynamicTypeSize', lines: [`.${value}`] };
      }
      return { type: 'String', lines: [swiftString(value)] };
    case 'boolean':
      if (typeof value !== 'boolean') throw new TokenError(`${id}: $type boolean cần true/false`);
      return { type: 'Bool', lines: [String(value)] };
    case 'fontFamily':
      if (typeof value !== 'string' || !value) throw new TokenError(`${id}: fontFamily cần tên font`);
      return { type: 'String', lines: [swiftString(value)] };
    case 'fontWeight':
      if (!Number.isInteger(value) || value < 1 || value > 1000) throw new TokenError(`${id}: fontWeight cần số nguyên 1–1000`);
      return { type: 'Int', lines: [String(value)] };
    case 'typography':
      return { type: 'Tokens.Typography', lines: typography(value, id, resolveRef) };
    case 'shadow':
      return { type: 'Tokens.Shadow', lines: shadow(value, id, resolveRef) };
    case 'polygon':
      return { type: '[CGPoint]', lines: polygon(value, id), note: '(x theo tỉ lệ bề rộng, y theo pt)' };
    case 'grid':
      return { type: 'Tokens.GridSpec', lines: [grid(value, id)] };
    case 'svgFilter':
      checkRefsInside(value, id);
      return { type: 'String', lines: [swiftString(JSON.stringify(value))], note: '(JSON tham số filter SVG)' };
    case 'keyframeAnimation':
      return { type: 'Tokens.KeyframeAnimation', lines: keyframeAnimation(value, id), note: motionNote(value) };
    case 'stateTransition':
      return { type: 'Tokens.StateTransition', lines: stateTransition(value, id), note: motionNote(value) };
    default:
      throw new TokenError(`${id}: $type "${type}" chưa có ánh xạ Swift trong export-swift.mjs`);
  }
}

function typography(v, id, resolveRef) {
  expectKeys(v, id, ['family', 'size', 'weight', 'line_height', 'letter_spacing', 'text_case']);
  const family = typeof v.family === 'string' && v.family.startsWith('{')
    ? resolveRef(v.family, `${id}.family`, 'fontFamily')?.swift
    : typeof v.family === 'string' ? swiftString(v.family) : null;
  if (!family) throw new TokenError(`${id}.family: cần tên font hoặc tham chiếu {font.family.*}`);
  const weight = typeof v.weight === 'string'
    ? resolveRef(v.weight, `${id}.weight`, 'fontWeight')?.swift
    : int(v.weight, `${id}.weight`);
  if (!weight) throw new TokenError(`${id}.weight: cần số hoặc tham chiếu {font.weight.*}`);
  const textCase = { none: 'nil', upper: '.uppercase', lower: '.lowercase' }[v.text_case];
  if (!textCase) throw new TokenError(`${id}.text_case: cần none, upper hoặc lower`);
  return call('Tokens.Typography', [
    ['family', family],
    ['size', num(v.size, `${id}.size`)],
    ['weight', weight],
    ['lineHeight', num(v.line_height, `${id}.line_height`)],
    ['letterSpacing', num(v.letter_spacing, `${id}.letter_spacing`)],
    ['textCase', textCase],
  ]);
}

function shadow(v, id, resolveRef) {
  if (!Array.isArray(v) || v.length === 0) throw new TokenError(`${id}: shadow cần mảng lớp`);
  const layers = v.map((layer, i) => {
    const where = `${id}[${i}]`;
    expectKeys(layer, where, ['x', 'y', 'blur', 'spread', 'color', 'alpha', 'inset']);
    let color = typeof layer.color === 'string' && layer.color.startsWith('{')
      ? resolveRef(layer.color, `${where}.color`, 'color')?.swift
      : colorLiteral(layer.color, `${where}.color`);
    if (typeof layer.alpha !== 'number' || layer.alpha < 0 || layer.alpha > 1) throw new TokenError(`${where}.alpha: cần số 0–1`);
    if (layer.alpha !== 1) color = `${color}.opacity(${num(layer.alpha, `${where}.alpha`)})`;
    if (typeof layer.inset !== 'boolean') throw new TokenError(`${where}.inset: cần true/false`);
    return `Tokens.Shadow.Layer(x: ${num(layer.x, `${where}.x`)}, y: ${num(layer.y, `${where}.y`)}, `
      + `blur: ${num(layer.blur, `${where}.blur`)}, spread: ${num(layer.spread, `${where}.spread`)}, `
      + `color: ${color}, inset: ${layer.inset})`;
  });
  return bracketList('Tokens.Shadow([', layers, '])');
}

function polygon(v, id) {
  if (!Array.isArray(v) || v.length < 2) throw new TokenError(`${id}: polygon cần mảng điểm [x, y]`);
  const points = v.map((p, i) => {
    if (!Array.isArray(p) || p.length !== 2) throw new TokenError(`${id}[${i}]: điểm phải là [x, y]`);
    return `CGPoint(x: ${num(p[0], `${id}[${i}][0]`)}, y: ${num(p[1], `${id}[${i}][1]`)})`;
  });
  return bracketList('[', points, ']');
}

function grid(v, id) {
  expectKeys(v, id, ['columns', 'cell_height', 'row_gap', 'column_gap']);
  return `Tokens.GridSpec(columns: ${int(v.columns, `${id}.columns`)}, cellHeight: ${num(v.cell_height, `${id}.cell_height`)}, `
    + `rowGap: ${num(v.row_gap, `${id}.row_gap`)}, columnGap: ${num(v.column_gap, `${id}.column_gap`)})`;
}

function keyframeAnimation(v, id) {
  expectKeys(v, id, ['duration', 'easing', 'delay', 'stagger', 'iteration', 'fill_mode', 'origin', 'keyframes']);
  if (typeof v.stagger !== 'boolean') throw new TokenError(`${id}.stagger: cần true/false`);
  if (v.iteration !== 1 && v.iteration !== 'infinite') throw new TokenError(`${id}.iteration: cần 1 hoặc "infinite"`);
  if (!FILL_MODES.includes(v.fill_mode)) throw new TokenError(`${id}.fill_mode: cần ${FILL_MODES.join(', ')}`);
  if (!Array.isArray(v.origin) || v.origin.length !== 2) throw new TokenError(`${id}.origin: cần [x, y]`);
  if (!Array.isArray(v.keyframes) || v.keyframes.length < 2) throw new TokenError(`${id}.keyframes: cần ít nhất 2 mốc`);
  let last = -1;
  const frames = v.keyframes.map((kf, i) => {
    const where = `${id}.keyframes[${i}]`;
    if (!isObject(kf) || typeof kf.offset !== 'number' || kf.offset < 0 || kf.offset > 1 || kf.offset <= last) {
      throw new TokenError(`${where}.offset: cần số 0–1 tăng dần`);
    }
    last = kf.offset;
    return `Tokens.Keyframe(offset: ${num(kf.offset, `${where}.offset`)}, pose: ${pose(kf, where)})`;
  });
  return call('Tokens.KeyframeAnimation', [
    ['duration', msToSeconds(v.duration, `${id}.duration`)],
    ['easing', bezier(v.easing, `${id}.easing`)],
    ['delay', msToSeconds(v.delay, `${id}.delay`)],
    ['stagger', String(v.stagger)],
    ['repeats', String(v.iteration === 'infinite')],
    ['fillMode', `.${v.fill_mode}`],
    ['origin', `UnitPoint(x: ${num(v.origin[0], `${id}.origin[0]`)}, y: ${num(v.origin[1], `${id}.origin[1]`)})`],
    ['keyframes', bracketList('[', frames, ']')],
  ]);
}

function stateTransition(v, id) {
  expectKeys(v, id, ['duration', 'easing', 'delay', 'trigger', 'from', 'to', 'also'], ['preserve_3d']);
  if (!TRIGGERS.includes(v.trigger)) throw new TokenError(`${id}.trigger: cần ${TRIGGERS.join(', ')}`);
  if (!Array.isArray(v.also)) throw new TokenError(`${id}.also: cần mảng`);
  if ('preserve_3d' in v && typeof v.preserve_3d !== 'boolean') throw new TokenError(`${id}.preserve_3d: cần true/false`);
  const also = v.also.map((a, i) => {
    const where = `${id}.also[${i}]`;
    expectKeys(a, where, ['property', 'duration', 'easing']);
    const property = TRANSITION_PROPERTIES[a.property];
    if (!property) {
      throw new TokenError(`${where}.property: "${a.property}" chưa có trong StateTransition.Property (export-swift.mjs)`);
    }
    return `Tokens.StateTransition.Companion(property: .${property}, duration: ${msToSeconds(a.duration, `${where}.duration`)}, `
      + `easing: ${bezier(a.easing, `${where}.easing`)})`;
  });
  for (const side of ['from', 'to']) {
    if (isObject(v[side]) && 'offset' in v[side]) throw new TokenError(`${id}.${side}: không dùng offset`);
  }
  return call('Tokens.StateTransition', [
    ['duration', msToSeconds(v.duration, `${id}.duration`)],
    ['easing', bezier(v.easing, `${id}.easing`)],
    ['delay', msToSeconds(v.delay, `${id}.delay`)],
    ['trigger', `.${v.trigger}`],
    ['from', pose(v.from, `${id}.from`)],
    ['to', pose(v.to, `${id}.to`)],
    ['also', bracketList('[', also, ']')],
    ['preserve3d', String(v.preserve_3d === true)],
  ]);
}

function motionNote(v) {
  const parts = [`${v.duration} ms`, `cubic-bezier(${v.easing.join(', ')})`];
  if (v.delay) parts.push(`trễ ${v.delay} ms`);
  if (v.iteration === 'infinite') parts.push('lặp');
  return `(${parts.join(', ')})`;
}

function emitAgeLookups(byId, leafSwiftPath) {
  const out = ['// MARK: - Age group lookups', '', 'extension Tokens.AgeGroup {'];
  AGE_LOOKUPS.forEach((lookup, i) => {
    if (i > 0) out.push('');
    out.push(`    /// ${lookup.doc}`);
    out.push(`    public var ${lookup.property}: ${lookup.type} {`);
    out.push('        switch self {');
    for (const age of AGE_GROUPS) {
      const id = `${lookup.group}.${age}`;
      if (!byId.has(id)) throw new TokenError(`${id}: thiếu (Tokens.AgeGroup.${lookup.property} cần đủ ${AGE_GROUPS.join(', ')})`);
      out.push(`        case .${age}: ${leafSwiftPath.get(id)}`);
    }
    out.push('        }', '    }');
  });
  out.push('}');
  return out;
}

