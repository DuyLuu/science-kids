// export-swift.mjs (SK-007): packages/design-tokens/tokens.json → Tokens.swift for the
// DesignSystem module of the iOS app. Node only, no dependencies.
//
//   node scripts/export-swift.mjs                  write Tokens.swift
//   node scripts/export-swift.mjs --check          compare in memory, exit 1 and name the tokens that differ
//   options: --tokens <tokens.json> --out <Tokens.swift>
//
// One leaf in tokens.json = one `public static let` in Tokens.swift. The output depends only on
// tokens.json (key order as in the file, no timestamp), so two runs give the same bytes.

