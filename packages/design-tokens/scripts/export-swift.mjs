// Reading tokens.json

/** Walks the tree, checks names and shapes, returns leaves and groups in file order. */
export function readTree(tokens) {
  if (!isObject(tokens)) throw new TokenError('tokens.json: gốc phải là object');
  const leaves = [];
  const groups = [];
  walk(tokens, [], leaves, groups);
  return { leaves, groups };
}

function walk(node, path, leaves, groups) {
  for (const [key, child] of Object.entries(node)) {
    const id = [...path, key].join('.');
    if (key.startsWith('$')) {
      if (key !== '$description') throw new TokenError(`${path.join('.') || '<gốc>'}: khoá ${key} không dùng ở nhóm`);
      continue;
    }
    if (!KEY_RE.test(key)) throw new TokenError(`${id}: khoá không phải snake_case`);
    if (!isObject(child)) throw new TokenError(`${id}: phải là nhóm hoặc lá (object)`);
    if ('$value' in child) {
      for (const k of Object.keys(child)) {
        if (!['$value', '$type', '$description'].includes(k)) throw new TokenError(`${id}: khoá lạ ${k} trong lá`);
      }
      if (typeof child.$type !== 'string') throw new TokenError(`${id}: thiếu $type`);
      leaves.push({ id, path: [...path, key], key, type: child.$type, value: child.$value, description: child.$description });
    } else {
      groups.push({ id, path: [...path, key], key, description: child.$description, node: child });
      walk(child, [...path, key], leaves, groups);
    }
  }
}

function isObject(v) {
  return v !== null && typeof v === 'object' && !Array.isArray(v);
}

// ---------------------------------------------------------------------------------------------
// Layout: a tree of Swift containers mirroring the JSON groups

function buildContainers(tokens) {
  const top = [];
  const leafSwiftPath = new Map();
  const usedTop = new Set(TOKENS_TYPES);

  const addTop = (groupPath, node, description) => {
    const id = groupPath.join('.');
    const backed = TYPE_BACKED[id];
    const name = backed ? backed.name : RENAME[id] ?? upperCamel(groupPath[groupPath.length - 1]);
    if (SWIFT_TYPES_USED.has(name)) throw new TokenError(`${id}: nhóm tên ${name} sẽ che kiểu Swift cùng tên; đổi tên nhóm`);
    if (!backed && usedTop.has(name)) throw new TokenError(`${id}: tên Swift Tokens.${name} bị trùng`);
    usedTop.add(name);
    const container = makeContainer(groupPath, node, description, ['Tokens', name], backed);
    container.kind = backed ? 'extension' : 'enum';
    top.push(container);
  };

  const makeContainer = (groupPath, node, description, swiftPath, backed) => {
    const id = groupPath.join('.');
    const container = { id, name: swiftPath[swiftPath.length - 1], swiftPath, description, items: [] };
    const used = new Set(backed ? backed.members : []);
    for (const [key, child] of Object.entries(node)) {
      if (key.startsWith('$')) continue;
      const childPath = [...groupPath, key];
      const childId = childPath.join('.');
      if ('$value' in child) {
        const name = swiftIdentifier(lowerCamel(key), childId);
        if (used.has(name)) throw new TokenError(`${childId}: tên Swift ${name} bị trùng trong ${swiftPath.join('.')}`);
        used.add(name);
        leafSwiftPath.set(childId, [...swiftPath, name].join('.'));
        container.items.push({ leafId: childId, name });
      } else {
        const name = swiftIdentifier(RENAME[childId] ?? upperCamel(key), childId);
        if (SWIFT_TYPES_USED.has(name)) throw new TokenError(`${childId}: nhóm tên ${name} sẽ che kiểu Swift cùng tên; đổi tên nhóm`);
        if (used.has(name)) throw new TokenError(`${childId}: tên Swift ${name} bị trùng trong ${swiftPath.join('.')}`);
        used.add(name);
        container.items.push({ group: makeContainer(childPath, child, child.$description, [...swiftPath, name], null) });
      }
    }
    return container;
  };

  for (const [key, child] of Object.entries(tokens)) {
    if (key.startsWith('$')) continue;
    if (FLATTEN.has(key)) {
      for (const [subKey, sub] of Object.entries(child)) {
        if (subKey.startsWith('$')) continue;
        if ('$value' in sub) throw new TokenError(`${key}.${subKey}: lá nằm thẳng dưới nhóm ${key} (nhóm này chỉ chứa nhóm con)`);
        addTop([key, subKey], sub, sub.$description);
      }
    } else if ('$value' in child) {
      throw new TokenError(`${key}: lá ở gốc tokens.json; đặt vào một nhóm`);
    } else {
      addTop([key], child, child.$description);
    }
  }
  return { top, leafSwiftPath };
}

