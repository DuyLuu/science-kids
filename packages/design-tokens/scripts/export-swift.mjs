// ---------------------------------------------------------------------------------------------
// Naming

const KEY_RE = /^[a-z0-9]+(_[a-z0-9]+)*$/;
const REF_RE = /^\{([a-z0-9_]+(?:\.[a-z0-9_]+)*)\}$/;
/** First doc line of every token constant: /// `path.to.leaf` … (needs at least one dot). */
export const MARKER_RE = /^[ \t]*\/\/\/ `([a-z0-9_]+(?:\.[a-z0-9_]+)+)`/gm;

// Swift keywords that need backticks when used as an identifier (The Swift Programming Language,
// "Keywords and Punctuation"), plus member names that clash with Swift built-ins.
const SWIFT_KEYWORDS = new Set([
  'associatedtype', 'borrowing', 'class', 'consuming', 'deinit', 'enum', 'extension', 'fileprivate',
  'func', 'import', 'init', 'inout', 'internal', 'let', 'nonisolated', 'open', 'operator', 'private',
  'precedencegroup', 'protocol', 'public', 'rethrows', 'static', 'struct', 'subscript', 'typealias',
  'var', 'break', 'case', 'catch', 'continue', 'default', 'defer', 'do', 'else', 'fallthrough', 'for',
  'guard', 'if', 'in', 'repeat', 'return', 'throw', 'switch', 'where', 'while', 'Any', 'as', 'await',
  'false', 'is', 'nil', 'self', 'Self', 'super', 'throws', 'true', 'try', 'Type', 'Protocol',
]);

/** `snake_case` → `lowerCamelCase` (`title_xl` → `titleXl`, `paper_1` → `paper1`). */
export function lowerCamel(key) {
  return key.split('_').map((part, i) => (i === 0 ? part : part.charAt(0).toUpperCase() + part.slice(1))).join('');
}

/** `snake_case` → `UpperCamelCase`, for group namespaces. */
export function upperCamel(key) {
  const s = lowerCamel(key);
  return s.charAt(0).toUpperCase() + s.slice(1);
}

/** Identifier usable in Swift: backticks around keywords; names cannot start with a digit. */
export function swiftIdentifier(name, where) {
  if (/^[0-9]/.test(name)) {
    throw new TokenError(`${where}: tên Swift "${name}" bắt đầu bằng số; đổi khoá trong tokens.json (ví dụ thêm chữ như space.s12)`);
  }
  return SWIFT_KEYWORDS.has(name) ? `\`${name}\`` : name;
}

