/** Swift number literal. */
export function num(n, where) {
  if (typeof n !== 'number' || !Number.isFinite(n)) throw new TokenError(`${where}: cần số, gặp ${JSON.stringify(n)}`);
  const s = String(n);
  if (/e/i.test(s)) throw new TokenError(`${where}: số ${s} quá lớn hoặc quá nhỏ để ghi thẳng`);
  return s;
}

function int(n, where) {
  if (!Number.isInteger(n)) throw new TokenError(`${where}: cần số nguyên, gặp ${JSON.stringify(n)}`);
  return String(n);
}

function msToSeconds(ms, where) {
  if (typeof ms !== 'number' || ms < 0) throw new TokenError(`${where}: thời lượng phải là số ms ≥ 0`);
  return num(ms / 1000, where);
}

function swiftString(s) {
  return `"${s.replace(/\\/g, '\\\\').replace(/"/g, '\\"').replace(/\n/g, '\\n').replace(/\r/g, '\\r').replace(/\t/g, '\\t')}"`;
}

function colorLiteral(hex, where) {
  const m = /^#([0-9a-fA-F]{2})([0-9a-fA-F]{2})([0-9a-fA-F]{2})$/.exec(hex);
  if (!m) throw new TokenError(`${where}: màu phải là #RRGGBB hoặc tham chiếu {…}, gặp ${JSON.stringify(hex)}`);
  const [r, g, b] = m.slice(1).map((h) => `0x${h.toUpperCase()}`);
  return `Color(.sRGB, red: ${r} / 255, green: ${g} / 255, blue: ${b} / 255)`;
}

function expectKeys(obj, where, required, optional = []) {
  if (!isObject(obj)) throw new TokenError(`${where}: cần object`);
  for (const k of required) if (!(k in obj)) throw new TokenError(`${where}: thiếu ${k}`);
  for (const k of Object.keys(obj)) {
    if (!required.includes(k) && !optional.includes(k)) {
      throw new TokenError(`${where}: khoá lạ ${k} (export-swift.mjs chưa biết; thêm ánh xạ trước khi dùng)`);
    }
  }
}

function bezier(v, where) {
  if (!Array.isArray(v) || v.length !== 4) throw new TokenError(`${where}: easing phải là 4 số cubic-bezier`);
  return `Tokens.CubicBezier(${v.map((n, i) => num(n, `${where}[${i}]`)).join(', ')})`;
}

function pose(obj, where) {
  if (!isObject(obj)) throw new TokenError(`${where}: cần object`);
  const known = POSE_PROPS.map(([k]) => k);
  for (const k of Object.keys(obj)) {
    if (k !== 'offset' && !known.includes(k)) {
      throw new TokenError(`${where}: thuộc tính motion lạ ${k} (thêm vào Tokens.Pose trong export-swift.mjs)`);
    }
  }
  const args = [];
  for (const [jsonKey, swiftName, kind] of POSE_PROPS) {
    if (!(jsonKey in obj)) continue;
    const v = num(obj[jsonKey], `${where}.${jsonKey}`);
    args.push(`${swiftName}: ${kind === 'degrees' ? `.degrees(${v})` : v}`);
  }
  return `Tokens.Pose(${args.join(', ')})`;
}

function bracketList(open, items, close) {
  if (items.length === 0) return [`${open}${close}`];
  return [open, ...items.map((s) => `    ${s},`), close];
}

/** Lines of `Name(\n    label: value,\n …)`; nested multi-line values are indented. */
function call(name, args) {
  const lines = [`${name}(`];
  args.forEach(([label, value], i) => {
    const valueLines = Array.isArray(value) ? value : [value];
    const sep = i === args.length - 1 ? '' : ',';
    valueLines.forEach((vl, j) => {
      const prefix = j === 0 ? `    ${label}: ` : '    ';
      lines.push(`${prefix}${vl}${j === valueLines.length - 1 ? sep : ''}`);
    });
  });
  lines.push(')');
  return lines;
}

